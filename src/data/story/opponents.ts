const STORY_OPPONENT_IDS: ReadonlySet<string> = new Set(STORY_OPPONENTS.map((opponent) => opponent.id));

/** Whether `id` names a Story-only opponent (never a Tower avatar). */
export function isStoryOpponentId(id: string): boolean {
  return STORY_OPPONENT_IDS.has(id);
}

/** Every opponent id a story duel can name: the Story-only opponents, then the Tower avatars. */
export function storyAvatarIds(): string[] {
  return [...STORY_OPPONENTS.map((opponent) => opponent.id), ...AVATARS.map((avatar) => avatar.id)];
}

/**
 * The one opponent lookup every story path uses (StoryProgress, the headless
 * run, the duel screen's story and replay branches, the content check): a
 * Story-only opponent first, then the Tower roster. Throws on an unknown id,
 * like avatarById.
 */
export function storyAvatarById(id: string): Avatar {
  return STORY_OPPONENTS.find((opponent) => opponent.id === id) ?? avatarById(id);
}
